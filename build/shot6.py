import asyncio
from playwright.async_api import async_playwright
async def main():
    async with async_playwright() as p:
        b=await p.chromium.launch(executable_path="/usr/bin/google-chrome",args=["--no-sandbox"])
        errs=[]
        ctx=await b.new_context(viewport={"width":1440,"height":900})
        pg=await ctx.new_page(); pg.on("pageerror",lambda e: errs.append(str(e)))
        pg.on("console",lambda m: errs.append("console: "+m.text) if m.type=="error" and "404" not in m.text else None)
        async def shot(n): await pg.screenshot(path=f"build/f_{n}.png")
        await pg.goto("http://localhost:8765/index.html"); await pg.wait_for_timeout(1800); await shot("overview")
        await pg.click("button[data-act=hosps]"); await pg.wait_for_timeout(1200)
        await pg.click("button[data-hf=trauma]"); await pg.wait_for_timeout(1200); await shot("hosp_trauma")
        await pg.click(".dh button[data-place=VMC]"); await pg.wait_for_timeout(1200); await shot("vmc")
        await pg.click("#laybtn"); await pg.click("#lay input[data-l=lm]"); await pg.wait_for_timeout(300); await pg.click("#laybtn")
        await pg.goto("http://localhost:8765/index.html#station-71"); await pg.wait_for_timeout(1500); await shot("st71_layers")
        await pg.click("#tabs button[data-mode=study]"); await pg.wait_for_timeout(1000); await shot("study")
        await pg.click("button[data-game=pin]"); await pg.wait_for_timeout(600); await shot("setup_pin")
        await pg.click("button[data-count='5']"); await pg.click("button[data-act=start]"); await pg.wait_for_timeout(1200); await shot("pin_ask")
        await pg.mouse.click(520,430); await pg.wait_for_timeout(300); await shot("pin_mid"); await pg.wait_for_timeout(1300); await shot("pin_reveal")
        for i in range(4):
            await pg.keyboard.press("Enter"); await pg.wait_for_timeout(900); await pg.mouse.click(450+i*30,420); await pg.wait_for_timeout(1500)
        await pg.keyboard.press("Enter"); await pg.wait_for_timeout(1300); await shot("pin_done")
        await pg.click("button[data-act=studyhome] >> nth=0"); await pg.wait_for_timeout(600)
        await pg.click("button[data-game=numbers]"); await pg.click("button[data-count='5']"); await pg.click("button[data-act=start]"); await pg.wait_for_timeout(1200); await shot("num_ask")
        await pg.keyboard.press("2"); await pg.wait_for_timeout(1000); await shot("num_reveal")
        await pg.click("button[data-act=studyhome] >> nth=0"); await pg.wait_for_timeout(600)
        await pg.click("button[data-game=hosp]"); await pg.click("button[data-count='5']"); await pg.click("button[data-act=start]"); await pg.wait_for_timeout(1200)
        await pg.keyboard.press("1"); await pg.wait_for_timeout(1200); await shot("hosp_reveal")
        await pg.click("button[data-act=studyhome] >> nth=0"); await pg.wait_for_timeout(600)
        await pg.click("button[data-game=find]"); await pg.click("button[data-cat=hospital]"); await pg.click("button[data-act=start]"); await pg.wait_for_timeout(1200)
        await pg.mouse.click(600,400); await pg.wait_for_timeout(1600); await shot("find_reveal")
        await pg.click("button[data-act=studyhome] >> nth=0"); await pg.wait_for_timeout(600)
        await pg.click("button[data-game=rig]"); await pg.click("button[data-act=start]"); await pg.wait_for_timeout(1200)
        box=await pg.evaluate("(()=>{const m=document.querySelector('.mk.game');const r=m.getBoundingClientRect();return [r.x+r.width/2,r.y+r.height/2]})()")
        await pg.mouse.click(*box); await pg.wait_for_timeout(1000); await shot("rig_reveal")
        await ctx.close()
        ctx=await b.new_context(viewport={"width":390,"height":844}); pg=await ctx.new_page(); pg.on("pageerror",lambda e: errs.append("mob "+str(e)))
        await pg.goto("http://localhost:8765/index.html"); await pg.wait_for_timeout(1500); await pg.screenshot(path="build/f_mob_over.png")
        await pg.click("#tabs button[data-mode=study]"); await pg.wait_for_timeout(800)
        await pg.click("button[data-game=name]"); await pg.wait_for_timeout(700); await pg.screenshot(path="build/f_mob_setup.png")
        await pg.click("button[data-act=start]"); await pg.wait_for_timeout(1300); await pg.screenshot(path="build/f_mob_name.png")
        await pg.click(".choices button >> nth=0"); await pg.wait_for_timeout(1000); await pg.screenshot(path="build/f_mob_name_rev.png")
        print("\n".join(errs) or "no errors"); await b.close()
asyncio.run(main())
